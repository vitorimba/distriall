#!/bin/bash
# ============================================================================
# AIOX New Project — One Command Setup
# ============================================================================
# Usage:
#   bash bin/aiox-new-project.sh <project-name> [projects-base]
#
# Examples:
#   bash bin/aiox-new-project.sh meu-saas
#   bash bin/aiox-new-project.sh meu-saas "D:/projetos"
#
# What it does:
#   1. Creates project folder
#   2. Copies framework (.aiox-core), config (.claude), squads, infrastructure
#   3. Creates .aiox/sync-config.yaml with correct local paths
#   4. Initializes git
#   5. Ready to use — all agents and squads available
# ============================================================================

set -e

# ── Args ────────────────────────────────────────────────────────────────────

PROJECT_NAME="$1"
PROJECTS_BASE="${2:-$(dirname "$(cd "$(dirname "$0")/.." && pwd)")}"
TEMPLATE_DIR="$(cd "$(dirname "$0")/.." && pwd)"

if [ -z "$PROJECT_NAME" ]; then
  echo ""
  echo "  AIOX New Project"
  echo "  ────────────────"
  echo ""
  echo "  Usage:  bash bin/aiox-new-project.sh <project-name> [projects-base]"
  echo ""
  echo "  Example:"
  echo "    bash bin/aiox-new-project.sh meu-saas"
  echo "    bash bin/aiox-new-project.sh meu-saas \"D:/projetos\""
  echo ""
  exit 1
fi

PROJECT_DIR="$PROJECTS_BASE/$PROJECT_NAME"

# ── Checks ──────────────────────────────────────────────────────────────────

if [ -d "$PROJECT_DIR" ]; then
  echo "ERRO: Pasta '$PROJECT_DIR' ja existe."
  exit 1
fi

if [ ! -d "$TEMPLATE_DIR/.aiox-core" ]; then
  echo "ERRO: Template AIOX nao encontrado em '$TEMPLATE_DIR'."
  echo "      Certifique-se de rodar este script de dentro do projeto raiz."
  exit 1
fi

# ── Go ──────────────────────────────────────────────────────────────────────

echo ""
echo "  AIOX New Project"
echo "  ────────────────"
echo "  Project:  $PROJECT_NAME"
echo "  Path:     $PROJECT_DIR"
echo "  Template: $TEMPLATE_DIR"
echo ""

# 1. Create project directory
echo "[1/7] Criando pasta do projeto..."
mkdir -p "$PROJECT_DIR"

# 2. Copy framework core
echo "[2/7] Copiando framework (.aiox-core)..."
cp -r "$TEMPLATE_DIR/.aiox-core" "$PROJECT_DIR/.aiox-core"

# 3. Copy Claude Code config (agents, rules, hooks, commands)
echo "[3/7] Copiando configuracao Claude Code (.claude)..."
cp -r "$TEMPLATE_DIR/.claude" "$PROJECT_DIR/.claude"
# Remove settings.local.json (machine-specific)
rm -f "$PROJECT_DIR/.claude/settings.local.json"

# 4. Copy squads
echo "[4/7] Copiando squads..."
mkdir -p "$PROJECT_DIR/squads"
cp -r "$TEMPLATE_DIR/squads/"* "$PROJECT_DIR/squads/" 2>/dev/null || true

# 5. Copy infrastructure (runner, validators)
echo "[5/7] Copiando infrastructure..."
if [ -d "$TEMPLATE_DIR/infrastructure" ]; then
  cp -r "$TEMPLATE_DIR/infrastructure" "$PROJECT_DIR/infrastructure"
fi

# 6. Setup local config
echo "[6/7] Configurando .aiox/ local..."
mkdir -p "$PROJECT_DIR/.aiox"

# Copy template
if [ -f "$TEMPLATE_DIR/.aiox/sync-config.template.yaml" ]; then
  cp "$TEMPLATE_DIR/.aiox/sync-config.template.yaml" "$PROJECT_DIR/.aiox/sync-config.template.yaml"
fi

# Generate sync-config.yaml with correct paths
cat > "$PROJECT_DIR/.aiox/sync-config.yaml" << EOF
# Sync Template Configuration — LOCAL
# Generated by aiox-new-project.sh on $(date +%Y-%m-%d)

template_path: "$TEMPLATE_DIR"
projects_base: "$PROJECTS_BASE"
export_dir: "$PROJECT_DIR/.aiox/exports"

exclude_projects: []

defaults:
  layers: "all"
  dry_run: false
  force: false
  skip_commit: false
EOF

# Copy .gitignore
if [ -f "$TEMPLATE_DIR/.gitignore" ]; then
  cp "$TEMPLATE_DIR/.gitignore" "$PROJECT_DIR/.gitignore"
fi

# Create project structure
mkdir -p "$PROJECT_DIR/docs/stories"
mkdir -p "$PROJECT_DIR/docs/prd"
mkdir -p "$PROJECT_DIR/docs/architecture"
mkdir -p "$PROJECT_DIR/src"
mkdir -p "$PROJECT_DIR/tests"

# 7. Init git
echo "[7/7] Inicializando git..."
cd "$PROJECT_DIR"
git init -q
git add .
git commit -q -m "chore: bootstrap AIOX project from template"

# ── Done ────────────────────────────────────────────────────────────────────

# Count what was installed
AGENT_COUNT=$(find .claude/commands -name "*.md" 2>/dev/null | wc -l | tr -d ' ')
SQUAD_COUNT=$(find squads -maxdepth 1 -type d 2>/dev/null | tail -n +2 | wc -l | tr -d ' ')

echo ""
echo "  ════════════════════════════════════════"
echo "  PROJETO CRIADO COM SUCESSO"
echo "  ════════════════════════════════════════"
echo ""
echo "  Path:     $PROJECT_DIR"
echo "  Agentes:  $AGENT_COUNT slash commands"
echo "  Squads:   $SQUAD_COUNT squads"
echo ""
echo "  Proximos passos:"
echo "    cd $PROJECT_DIR"
echo "    claude                          # abrir Claude Code"
echo "    /AIOX:agents:dev               # ativar agente Dev"
echo "    gh repo create $PROJECT_NAME --private --source=. --push"
echo ""
echo "  ════════════════════════════════════════"
echo ""
